-- TABLAS CATÁLOGO Y PRINCIPALES-------------------------------------------------------------------

CREATE TABLE categorias (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(50) NOT NULL UNIQUE,
    descripcion VARCHAR2(150)
);

CREATE TABLE marcas (
    id_marca NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_marca VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE ubicaciones (
    id_ubicacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_ubicacion VARCHAR2(20) NOT NULL UNIQUE,
    descripcion VARCHAR2(100)
);

CREATE TABLE proveedores (
    id_proveedor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit_empresa VARCHAR2(15) NOT NULL UNIQUE,
    nombre_empresa VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(15) NOT NULL,
    contacto_principal VARCHAR2(100)
);

CREATE TABLE clientes (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit VARCHAR2(15) DEFAULT 'CF' NOT NULL,
    nombre_completo VARCHAR2(100) NOT NULL,
    direccion VARCHAR2(200),
    telefono VARCHAR2(15)
);

CREATE TABLE empleados (
    id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR2(100) NOT NULL,
    cargo VARCHAR2(50) NOT NULL
);

CREATE TABLE metodos_pago (
    id_metodo_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_metodo VARCHAR2(50) NOT NULL UNIQUE
);


-- TABLAS TRANSACCIONALES Y DE PRODUCTOS

CREATE TABLE productos (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_barras VARCHAR2(50) UNIQUE NOT NULL,
    nombre_producto VARCHAR2(100) NOT NULL,
    precio_compra NUMBER(10,2) NOT NULL CHECK (precio_compra > 0),
    precio_venta NUMBER(10,2) NOT NULL CHECK (precio_venta > 0),
    stock_actual NUMBER NOT NULL CHECK (stock_actual >= 0),
    id_categoria NUMBER NOT NULL,
    id_marca NUMBER NOT NULL,
    id_ubicacion NUMBER NOT NULL,
    CONSTRAINT fk_prod_categorias FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria),
    CONSTRAINT fk_prod_marcas FOREIGN KEY (id_marca) REFERENCES marcas(id_marca),
    CONSTRAINT fk_prod_ubicaciones FOREIGN KEY (id_ubicacion) REFERENCES ubicaciones(id_ubicacion)
);

-- Tabla intermedia para múltiples proveedores por producto
CREATE TABLE productos_proveedores (
    id_prod_prov NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL,
    id_proveedor NUMBER NOT NULL,
    CONSTRAINT fk_pp_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
    CONSTRAINT fk_pp_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor),
    CONSTRAINT un_prod_prov UNIQUE (id_producto, id_proveedor)
);

-- Tabla de Movimientos de Inventario (Requerimiento Fase 2)
CREATE TABLE movimientos_inventario (
    id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL,
    tipo_movimiento VARCHAR2(20) NOT NULL CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'DEVOLUCION', 'DAÑADO', 'AJUSTE')),
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    stock_anterior NUMBER NOT NULL CHECK (stock_anterior >= 0),
    stock_nuevo NUMBER NOT NULL CHECK (stock_nuevo >= 0),
    fecha_movimiento TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    referencia VARCHAR2(100),
    CONSTRAINT fk_mov_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
);

CREATE TABLE compras_encabezado (
    id_compra NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura_proveedor VARCHAR2(50) NOT NULL,
    fecha_compra TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_compra NUMBER(10,2) DEFAULT 0,
    id_proveedor NUMBER NOT NULL,
    CONSTRAINT fk_compras_proveedores FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor)
);

CREATE TABLE compras_detalle (
    id_detalle_compra NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_costo_unidad NUMBER(10,2) NOT NULL CHECK (precio_costo_unidad > 0),
    subtotal NUMBER(10,2) GENERATED ALWAYS AS (cantidad * precio_costo_unidad),
    CONSTRAINT fk_detallecompra_encabezado FOREIGN KEY (id_compra) REFERENCES compras_encabezado(id_compra),
    CONSTRAINT fk_detallecompra_productos FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
);

CREATE TABLE facturas_encabezado (
    id_factura NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura VARCHAR2(20) UNIQUE NOT NULL,
    fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_factura NUMBER(10,2) DEFAULT 0,
    id_cliente NUMBER NOT NULL,
    id_empleado NUMBER NOT NULL,
    CONSTRAINT fk_facturas_clientes FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    CONSTRAINT fk_facturas_empleados FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado)
);

CREATE TABLE facturas_detalle (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMBER(10,2) NOT NULL CHECK (precio_unitario > 0),
    subtotal NUMBER(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario),
    CONSTRAINT fk_detalle_factura FOREIGN KEY (id_factura) REFERENCES facturas_encabezado(id_factura),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
);

CREATE TABLE pagos_factura (
    id_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto NUMBER(10,2) NOT NULL CHECK (monto > 0),
    id_factura NUMBER NOT NULL,
    id_metodo_pago NUMBER NOT NULL,
    CONSTRAINT fk_pagos_factura FOREIGN KEY (id_factura) REFERENCES facturas_encabezado(id_factura),
    CONSTRAINT fk_pagos_metodos FOREIGN KEY (id_metodo_pago) REFERENCES metodos_pago(id_metodo_pago)
);


