--Vistas Solicitadas

CREATE OR REPLACE VIEW vw_historial_operaciones AS
SELECT 
    'COMPRA' AS tipo_operacion,
    e.nombre_empresa AS entidad,
    c.numero_factura_proveedor AS documento,
    c.fecha_compra AS fecha,
    c.total_compra AS monto
FROM compras_encabezado c
JOIN proveedores e ON c.id_proveedor = e.id_proveedor
UNION ALL
SELECT 
    'VENTA' AS tipo_operacion,
    cl.nombre_completo AS entidad,
    f.numero_factura AS documento,
    f.fecha_emision AS fecha,
    f.total_factura AS monto
FROM facturas_encabezado f
JOIN clientes cl ON f.id_cliente = cl.id_cliente;
/

CREATE OR REPLACE VIEW vw_inventario_critico AS
SELECT 
    p.id_producto,
    p.codigo_barras,
    p.nombre_producto,
    p.stock_actual,
    cat.nombre_categoria,
    u.codigo_ubicacion
FROM productos p
JOIN categorias cat ON p.id_categoria = cat.id_categoria
JOIN ubicaciones u ON p.id_ubicacion = u.id_ubicacion
WHERE p.stock_actual <= 10;
