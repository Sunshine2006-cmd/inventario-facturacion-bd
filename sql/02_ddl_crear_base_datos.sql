--Procedimiento Almacenado: Proceso de Compra e Inventario

CREATE OR REPLACE PROCEDURE registrar_compra (
    p_nit_proveedor IN VARCHAR2,
    p_num_factura IN VARCHAR2,
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER,
    p_precio_costo IN NUMBER
) AS
    v_id_proveedor NUMBER;
    v_id_compra NUMBER;
    v_stock_actual NUMBER;
BEGIN
    SELECT id_proveedor INTO v_id_proveedor FROM proveedores WHERE nit_empresa = p_nit_proveedor;
    
    INSERT INTO compras_encabezado (numero_factura_proveedor, id_proveedor)
    VALUES (p_num_factura, v_id_proveedor)
    RETURNING id_compra INTO v_id_compra;
    
    INSERT INTO compras_detalle (id_compra, id_producto, cantidad, precio_costo_unidad)
    VALUES (v_id_compra, p_id_producto, p_cantidad, p_precio_costo);
    
    SELECT stock_actual INTO v_stock_actual FROM productos WHERE id_producto = p_id_producto;
    
    UPDATE productos 
    SET stock_actual = stock_actual + p_cantidad 
    WHERE id_producto = p_id_producto;
    
    INSERT INTO movimientos_inventario (id_producto, tipo_movimiento, cantidad, stock_anterior, stock_nuevo, referencia)
    VALUES (p_id_producto, 'ENTRADA', p_cantidad, v_stock_actual, v_stock_actual + p_cantidad, 'Compra Fac: ' || p_num_factura);
    
    COMMIT;
END;
/

--Procedimiento Almacenado: Proceso de Facturación

CREATE OR REPLACE PROCEDURE registrar_factura (
    p_nit_cliente IN VARCHAR2,
    p_id_empleado IN NUMBER,
    p_num_factura IN VARCHAR2,
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER
) AS
    v_id_cliente NUMBER;
    v_id_factura NUMBER;
    v_stock_actual NUMBER;
    v_precio_venta NUMBER;
BEGIN
    SELECT id_cliente INTO v_id_cliente FROM clientes WHERE nit = p_nit_cliente;
    
    SELECT stock_actual, precio_venta INTO v_stock_actual, v_precio_venta FROM productos WHERE id_producto = p_id_producto;
    
    IF v_stock_actual < p_cantidad THEN
        RAISE_APPLICATION_ERROR(-20001, 'Stock insuficiente para realizar la venta.');
    END IF;
    
    INSERT INTO facturas_encabezado (numero_factura, id_cliente, id_empleado)
    VALUES (p_num_factura, v_id_cliente, p_id_empleado)
    RETURNING id_factura INTO v_id_factura;
    
    INSERT INTO facturas_detalle (id_factura, id_producto, cantidad, precio_unitario)
    VALUES (v_id_factura, p_id_producto, p_cantidad, v_precio_venta);
    
    UPDATE productos 
    SET stock_actual = stock_actual - p_cantidad 
    WHERE id_producto = p_id_producto;
    
    INSERT INTO movimientos_inventario (id_producto, tipo_movimiento, cantidad, stock_anterior, stock_nuevo, referencia)
    VALUES (p_id_producto, 'SALIDA', p_cantidad, v_stock_actual, v_stock_actual - p_cantidad, 'Venta Factura: ' || p_num_factura);
    
    COMMIT;
END;
/

-- TRIGERS
-- 1. TRIGGER COMPUESTO PARA FACTURAS (Actualiza el total sin mutar la tabla)
CREATE OR REPLACE TRIGGER trg_actualizar_total_factura
FOR INSERT OR UPDATE OR DELETE ON facturas_detalle
COMPOUND TRIGGER

    TYPE t_totales IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_deltas t_totales;

    AFTER EACH ROW IS
        v_id NUMBER;
        v_monto_diff NUMBER := 0;
    BEGIN
        IF INSERTING THEN
            v_id := :NEW.id_factura;
            v_monto_diff := :NEW.cantidad * :NEW.precio_unitario;
        ELSIF DELETING THEN
            v_id := :OLD.id_factura;
            v_monto_diff := - (:OLD.cantidad * :OLD.precio_unitario);
        ELSIF UPDATING THEN
            IF :OLD.id_factura = :NEW.id_factura THEN
                v_id := :NEW.id_factura;
                v_monto_diff := (:NEW.cantidad * :NEW.precio_unitario) - (:OLD.cantidad * :OLD.precio_unitario);
            ELSE
                IF g_deltas.EXISTS(:OLD.id_factura) THEN
                    g_deltas(:OLD.id_factura) := g_deltas(:OLD.id_factura) - (:OLD.cantidad * :OLD.precio_unitario);
                ELSE
                    g_deltas(:OLD.id_factura) := - (:OLD.cantidad * :OLD.precio_unitario);
                END IF;
                v_id := :NEW.id_factura;
                v_monto_diff := :NEW.cantidad * :NEW.precio_unitario;
            END IF;
        END IF;

        IF v_id IS NOT NULL THEN
            IF g_deltas.EXISTS(v_id) THEN
                g_deltas(v_id) := g_deltas(v_id) + v_monto_diff;
            ELSE
                g_deltas(v_id) := v_monto_diff;
            END IF;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_idx NUMBER;
    BEGIN
        v_idx := g_deltas.FIRST;
        WHILE v_idx IS NOT NULL LOOP
            UPDATE facturas_encabezado
            SET total_factura = NVL(total_factura, 0) + g_deltas(v_idx)
            WHERE id_factura = v_idx;
            
            v_idx := g_deltas.NEXT(v_idx);
        END LOOP;
    END AFTER STATEMENT;

END trg_actualizar_total_factura;
/


